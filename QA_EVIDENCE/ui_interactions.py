"""Exercise visible SAMVED controls with the API fixture in ui_smoke.py."""
from playwright.sync_api import sync_playwright
from ui_smoke import BASE, Fixture

def main():
    fixture=Fixture()
    checks=[]
    with sync_playwright() as playwright:
        browser=playwright.chromium.launch(headless=True)
        page=browser.new_page(viewport={'width':1365,'height':900})
        page.route('**/api/v1/**',fixture.handle)
        errors=[]
        page.on('pageerror',lambda error: errors.append(str(error)))
        page.on('dialog',lambda dialog: dialog.accept())
        def open_page(path):
            page.goto(f'{BASE}/{path}')
            page.wait_for_timeout(300)
        def check(label,condition):
            if not condition: raise AssertionError(label)
            checks.append(label)

        open_page('auth/login.html')
        page.locator('#email').fill('test@example.com')
        page.locator('#password').fill('Password@123')
        page.locator('#loginForm button[type=submit]').click()
        page.wait_for_url('**/dashboard/index.html')
        check('login submits to API and redirects',any(c[1]=='auth/login' and c[0]=='POST' for c in fixture.calls))
        page.locator('#new-task-input').fill('Prepare portfolio')
        page.locator('#task-form button[type=submit]').click()
        page.wait_for_timeout(350)
        check('dashboard adds task',any(t['title']=='Prepare portfolio' for t in fixture.tasks))
        page.locator('#task-list-container input[type=checkbox]').check()
        page.wait_for_timeout(350)
        check('dashboard completes task',fixture.tasks[0]['status']=='COMPLETED')
        page.locator('#task-list-container button').click()
        page.wait_for_timeout(350)
        check('dashboard removes task',len(fixture.tasks)==0)
        page.get_by_role('button',name='Show all 1 roadmaps').click()
        check('roadmap catalogue toggle',page.get_by_role('button',name='Show fewer roadmaps').count()==1)
        page.get_by_role('button',name='Preview').first.click()
        page.wait_for_timeout(200)
        check('roadmap preview opens graph',page.locator('.rv-node').count()==1)
        page.get_by_role('button',name='Add to my roadmaps').first.click()
        page.wait_for_timeout(350)
        check('roadmap preference saves',any(item['slug']=='frontend' for item in fixture.saved))
        check('roadmap graph loads',page.locator('.rv-node').count()==1)
        page.get_by_role('button',name='Topics').click()
        check('roadmap topics view opens',page.locator('.rv-topic-list').is_visible())
        page.locator('.rv-topic-list button').first.click()
        page.wait_for_timeout(200)
        check('roadmap topic details open', 'Learn HTML structure.' in page.locator('.rv-panel').inner_text())
        page.locator('.rv-panel button').first.click()
        check('roadmap topic details close',not page.locator('.rv-panel').is_visible())
        page.get_by_role('button',name='Map',exact=True).click()
        check('roadmap map view opens',page.locator('.rv-stage').is_visible())
        before_zoom=page.locator('.rv-canvas').evaluate('el=>el.style.transform')
        page.get_by_role('button',name='Zoom in').click()
        check('roadmap zoom in changes scale',page.locator('.rv-canvas').evaluate('el=>el.style.transform')!=before_zoom)
        page.get_by_role('button',name='Fit',exact=True).click()
        check('roadmap fit control works',page.locator('.rv-canvas').evaluate('el=>el.style.transform').startswith('scale('))
        page.get_by_role('searchbox',name='Find a roadmap topic').fill('HTML')
        check('roadmap topic search filters list',page.locator('.rv-topic-list button:visible').count()==1)
        page.get_by_role('button',name='Open',exact=True).first.click()
        page.wait_for_timeout(200)
        check('roadmap activation saves',fixture.active_slug=='frontend')
        page.get_by_role('button',name='Remove',exact=True).first.click()
        page.wait_for_timeout(200)
        check('roadmap removal saves',fixture.saved==[])
        search=page.locator('.portal-search-input')
        search.fill('skills'); search.press('Enter')
        page.wait_for_url('**/profile/skills.html')
        check('header search opens a real page',page.locator('.portal-topbar').count()==1)

        page.locator('#skill').fill('Python')
        page.locator('#skillLevel').select_option(index=1)
        page.get_by_role('button',name='Add Skill').click()
        page.wait_for_timeout(250)
        check('skill saves to API',any(s['name']=='Python' for s in fixture.profile['skills']))
        page.locator('#skillsTableBody button').click()
        page.wait_for_timeout(250)
        check('skill delete saves to API',fixture.profile['skills']==[])

        open_page('profile/interests.html')
        page.get_by_role('button',name='Technology').click()
        page.get_by_role('button',name='Save Interests').click()
        page.wait_for_timeout(250)
        check('interests save', 'Technology' in fixture.profile['interests'])
        page.get_by_role('button',name='Reset Interests').click()
        page.wait_for_timeout(250)
        check('interests reset',fixture.profile['interests']==[])

        open_page('profile/strengths.html')
        page.locator('input[name=strength]').first.check()
        page.get_by_role('button',name='Save Strengths').click()
        page.wait_for_timeout(250)
        check('strengths save',len(fixture.profile['strengths'])==1)
        open_page('profile/values.html')
        page.locator('input[name=value]').first.check()
        page.get_by_role('button',name='Save Values').click()
        page.wait_for_timeout(250)
        check('values save',len(fixture.profile['values'])==1)

        open_page('profile/academic.html')
        page.get_by_role('button',name='+ Add Subject').click()
        check('academic add subject creates row',page.locator('.subject-row').count()==2)
        page.locator('.subject-row').last.get_by_role('button',name='Remove').click()
        check('academic remove subject removes row',page.locator('.subject-row').count()==1)
        page.locator('#educationLevel').select_option('Undergraduate')
        page.locator('#institution').fill('Test College')
        page.locator('#course').fill('CSE')
        page.locator('#academicPeriodType').select_option('Semester')
        page.locator('#academicPeriod').fill('3')
        page.locator('#overallScore').fill('82')
        page.locator('.subject-name').first.fill('Mathematics')
        page.locator('.subject-marks').first.fill('91')
        page.get_by_role('button',name='Save Academic Record').click()
        page.wait_for_timeout(250)
        check('academic record saves',len(fixture.profile['academics'])==1)
        page.locator('#academicRecords button').first.click()
        page.wait_for_timeout(250)
        check('academic record deletes',fixture.profile['academics']==[])

        open_page('profile/profile.html')
        page.get_by_role('button',name='Edit Profile').click()
        page.locator('#name').fill('Updated Student')
        page.locator('#saveButton').click()
        page.wait_for_timeout(300)
        check('profile edit saves',fixture.profile['name']=='Updated Student')
        page.locator('#currentPassword').fill('OldPassword@123')
        page.locator('#newPassword').fill('NewPassword@123')
        page.locator('#repeatPassword').fill('NewPassword@123')
        page.get_by_role('button',name='Change password').click()
        page.wait_for_timeout(250)
        check('password change submits',any(c[1]=='auth/password' and c[0]=='PUT' for c in fixture.calls))

        open_page('profile/careergoal.html')
        page.get_by_role('button',name='Save Career Goal').click()
        page.wait_for_timeout(300)
        check('career goal saves',any(c[1]=='students/me/review/career' and c[0]=='PUT' for c in fixture.calls))
        page.locator('#careerList button').click()
        page.wait_for_timeout(250)
        check('career goal delete resets to exploring',fixture.profile['careerGoal']['type']=='EXPLORING')

        open_page('assessment/assessment.html')
        page.locator('input[name=assessmentAnswer]').first.check()
        page.locator('#nextButton').click()
        page.locator('#backButton').click()
        check('assessment previous returns to first question','Question 1 of 8' in page.locator('#questionNumber').inner_text())
        for number in range(8):
            page.locator('input[name=assessmentAnswer]').first.check()
            page.locator('#nextButton').click()
            page.wait_for_timeout(80)
        check('assessment submits all answers',any(c[1]=='assessments/current/responses' and c[0]=='PUT' for c in fixture.calls))

        open_page('daily%20tasks/index.html')
        page.locator('#task-title').fill('Review course')
        page.locator('#task-deadline').fill('2026-10-30')
        page.get_by_role('button',name='Save Task').click()
        page.wait_for_timeout(350)
        check('daily tasks create',any(t['title']=='Review course' for t in fixture.tasks))
        page.get_by_role('button',name='Complete').first.click()
        page.wait_for_timeout(350)
        check('daily tasks complete',fixture.tasks[0]['status']=='COMPLETED')
        page.get_by_role('button',name='Edit').first.click()
        check('daily tasks edit opens form',page.locator('#task-title').input_value()=='Review course')
        page.get_by_role('button',name='Cancel').click()
        check('daily tasks cancel resets form',page.locator('#task-title').input_value()=='')
        page.get_by_role('button',name='Delete').first.click()
        page.wait_for_timeout(350)
        check('daily tasks delete',fixture.tasks==[])

        open_page('deadline%20system/index.html')
        page.locator('#deadline-title').fill('Submit report')
        page.locator('#deadline-date').fill('2026-10-31')
        page.get_by_role('button',name='Save task').click()
        page.wait_for_timeout(300)
        check('deadline form saves task',any(t['title']=='Submit report' for t in fixture.tasks))
        page.get_by_role('button',name='Mark complete').click()
        page.wait_for_timeout(300)
        check('deadline complete action',fixture.tasks[0]['status']=='COMPLETED')

        fixture.notifications.append({'id':1,'taskId':1,'dueDate':'2026-10-31',
                                      'message':'Report due soon','readAt':None})
        open_page('deadline%20system/index.html')
        page.get_by_role('button',name='Mark read').click()
        page.wait_for_timeout(250)
        check('reminder mark read',fixture.notifications[0]['readAt'] is not None)

        open_page('oppertunity%20page/index.html')
        page.get_by_role('button',name='Internships').click()
        page.wait_for_timeout(200)
        check('opportunity filter activates',page.get_by_role('button',name='Internships').get_attribute('class').find('active')>=0)
        check('opportunity filter queries internship API',any(c[1]=='opportunities' and 'type=INTERNSHIP' in c[3] for c in fixture.calls))
        check('opportunity link opens original listing',page.get_by_role('link',name='View original listing').first.get_attribute('href')=='https://example.org/apply')
        for label in ['All','Jobs','Hackathons','Competitions','Quizzes','Workshops','Events','Courses','Scholarships']:
            page.get_by_role('button',name=label,exact=True).click()
            page.wait_for_timeout(80)
            check(f'{label} filter activates', 'active' in page.get_by_role('button',name=label,exact=True).get_attribute('class'))

        open_page('recommondation%20page/index.html')
        check('recommendations show reasons and skill gaps',
              'Matches your interests' in page.locator('#recommendations-grid').inner_text()
              and 'CSS' in page.locator('#recommendations-grid').inner_text())

        open_page('charts/index.html')
        check('charts render live values',page.locator('#analytics-status').inner_text()=='Showing your saved account data.')
        page.set_viewport_size({'width':390,'height':844})
        page.locator('.samved-menu-toggle').click()
        check('mobile menu opens',page.locator('body').evaluate("el=>el.classList.contains('samved-nav-open')"))
        page.get_by_role('button',name='Sign out').click()
        page.wait_for_url('**/auth/login.html')
        check('sign out calls API and redirects',any(c[1]=='auth/logout' and c[0]=='POST' for c in fixture.calls))

        open_page('roadmap-explorer/index.html')
        page.locator('#query').fill('frontend')
        page.get_by_role('button',name='Find roadmaps').click()
        page.wait_for_timeout(200)
        check('public roadmap discovery works',page.get_by_role('link',name='View roadmap inside SAMVED').count()==1)
        page.get_by_role('button',name='Browse all').click()
        page.wait_for_timeout(200)
        check('public catalogue browse works',page.get_by_role('link',name='View roadmap inside SAMVED').count()==1)

        open_page('auth/register.html')
        page.locator('#name').fill('New User')
        page.locator('#email').fill('new@example.com')
        page.locator('#password').fill('Password@123')
        page.locator('#confirmPassword').fill('Mismatch@123')
        page.locator('#education').select_option('undergraduate')
        page.locator('#adultConfirmed').check()
        page.locator('#privacyAccepted').check()
        page.locator('#registerForm button[type=submit]').click()
        check('registration blocks mismatched passwords','Passwords do not match.' in page.locator('#registerMessage').inner_text())
        page.locator('#confirmPassword').fill('Password@123')
        page.locator('#registerForm button[type=submit]').click()
        page.wait_for_url('**/profile/profile.html')
        check('registration submits and signs in',any(c[1]=='auth/register' and c[0]=='POST' for c in fixture.calls))

        page.get_by_role('button',name='Delete my account and saved data').click()
        page.wait_for_url('**/auth/register.html')
        check('account delete submits',any(c[1]=='students/me' and c[0]=='DELETE' for c in fixture.calls))
        check('no browser script errors',not errors)
        browser.close()
    print('PASS:',len(checks),'checks')
    for item in checks: print('-',item)

if __name__=='__main__': main()
